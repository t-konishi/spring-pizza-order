
-- Export PIZZA schema DDL from Oracle FREEPDB1.
-- Run this script using SQL*Plus as SYSDBA.

WHENEVER OSERROR EXIT FAILURE
WHENEVER SQLERROR EXIT SQL.SQLCODE

SET ECHO OFF
SET VERIFY OFF
SET HEADING OFF
SET FEEDBACK OFF
SET PAGESIZE 0
SET LINESIZE 32767
SET LONG 2000000
SET LONGCHUNKSIZE 2000000
SET TRIMSPOOL ON
SET TRIMOUT ON

ALTER SESSION SET CONTAINER = FREEPDB1;

-- Remove environment-specific physical storage settings.
EXEC DBMS_METADATA.SET_TRANSFORM_PARAM(DBMS_METADATA.SESSION_TRANSFORM, 'SEGMENT_ATTRIBUTES', FALSE);

-- Generate executable SQL statements.
EXEC DBMS_METADATA.SET_TRANSFORM_PARAM(DBMS_METADATA.SESSION_TRANSFORM, 'SQLTERMINATOR', TRUE);

-- Include table constraints and foreign keys.
EXEC DBMS_METADATA.SET_TRANSFORM_PARAM(DBMS_METADATA.SESSION_TRANSFORM, 'CONSTRAINTS', TRUE);
EXEC DBMS_METADATA.SET_TRANSFORM_PARAM(DBMS_METADATA.SESSION_TRANSFORM, 'REF_CONSTRAINTS', TRUE);

-- Use the schema of the executing user when recreating tables.
EXEC DBMS_METADATA.SET_TRANSFORM_PARAM(DBMS_METADATA.SESSION_TRANSFORM, 'EMIT_SCHEMA', FALSE);

PROMPT -- PIZZA schema DDL for Oracle AI Database 26ai Free
PROMPT -- Execute only in an empty schema.

-- Parent tables
SELECT DBMS_METADATA.GET_DDL('TABLE', 'CUSTOMERS', 'PIZZA') FROM DUAL;
SELECT DBMS_METADATA.GET_DDL('TABLE', 'PIZZAS', 'PIZZA') FROM DUAL;

-- Order tables
SELECT DBMS_METADATA.GET_DDL('TABLE', 'ORDERS', 'PIZZA') FROM DUAL;
SELECT DBMS_METADATA.GET_DDL('TABLE', 'ORDER_ITEMS', 'PIZZA') FROM DUAL;
SELECT DBMS_METADATA.GET_DDL('TABLE', 'PAYMENTS', 'PIZZA') FROM DUAL;

EXIT
